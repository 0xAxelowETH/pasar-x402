// Copies the ABI + bytecode the runtime needs out of Hardhat's artifacts into
// src/generated/contracts.ts, so the services never depend on a Hardhat build.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const contracts = [
  ["PasarUSD", "contracts/PasarUSD.sol/PasarUSD.json"],
  ["TokenProbe", "contracts/TokenProbe.sol/TokenProbe.json"],
] as const;

let out = "// Generated by scripts/export-artifacts.ts — do not edit by hand.\n\n";
for (const [name, path] of contracts) {
  const artifact = JSON.parse(readFileSync(resolve(root, "artifacts", path), "utf8"));
  out += `export const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
  out += `export const ${name}Bytecode = "${artifact.bytecode}" as const;\n\n`;
  out += `export const ${name}DeployedBytecode = "${artifact.deployedBytecode}" as const;\n\n`;
}

mkdirSync(resolve(root, "src/generated"), { recursive: true });
writeFileSync(resolve(root, "src/generated/contracts.ts"), out);
console.log("Wrote src/generated/contracts.ts");
