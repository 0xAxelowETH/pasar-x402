// Creates a .env for BNB Smart Chain testnet with fresh wallets. Never overwrites an existing .env.
import { existsSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { resolve } from "node:path";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { ROOT } from "../src/config.js";

const envPath = resolve(ROOT, ".env");

if (existsSync(envPath)) {
  console.log(".env already exists — leaving it untouched.");
  console.log("Delete it first if you really want new wallets (you will lose access to the old ones).");
  process.exit(0);
}

const facilitatorKey = generatePrivateKey();
const sellerKey = generatePrivateKey();
const agentKey = generatePrivateKey();
const facilitator = privateKeyToAccount(facilitatorKey).address;
const seller = privateKeyToAccount(sellerKey).address;
const agent = privateKeyToAccount(agentKey).address;

writeFileSync(
  envPath,
  `# Pasar x402 — generated by "npm run setup". Keep this file private: it holds private keys.
NETWORK=bsc-testnet

# Pays gas for settlements and deploys/mints the pUSD test token. Fund it with test BNB.
FACILITATOR_PRIVATE_KEY=${facilitatorKey}
# Shared secret between the stalls and the facilitator.
FACILITATOR_API_KEY=${randomBytes(24).toString("hex")}

# Seller wallet: every stall pays here. Its key is only stored so you can move the earnings.
PAY_TO_ADDRESS=${seller}
SELLER_PRIVATE_KEY=${sellerKey}

# Shopping agent wallet: signs payments, never needs BNB.
AGENT_PRIVATE_KEY=${agentKey}
AGENT_DAILY_BUDGET_USD=1
AGENT_MAX_PER_PAYMENT_USD=0.1
AGENT_ALLOWED_HOSTS=127.0.0.1,localhost

# Optional
# TELEGRAM_BOT_TOKEN=
# TELEGRAM_ALLOWED_USERS=
# OLLAMA_MODEL=qwen2.5:1.5b
`,
);

console.log(`Created .env for BNB Smart Chain testnet.

  Facilitator (needs test BNB): ${facilitator}
  Seller (receives payments):   ${seller}
  Agent (pays, gasless):        ${agent}

Next:
  1. Get free test BNB for the facilitator: https://www.bnbchain.org/en/testnet-faucet
  2. npm run deploy     # deploys Pasar USD and mints 1,000 pUSD to the agent
  3. npm run dev        # facilitator + stalls + gateway
`);
